import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const browser = await chromium.launch({ channel: 'chrome' })
await mkdir('evidence', { recursive: true })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const click = async target => page.locator(`[data-target="${target}"]`).click()
  await page.goto('http://localhost:5183/#/halcyon-labs')
  assert.equal(await page.locator('.presenter-nav').count(), 0)
  await click('src-contract')
  assert.equal(await page.locator('.change[data-open]').count(), 1)
  await click('approve')
  await page.getByRole('textbox', { name: 'Outreach email' }).fill('Hi Priya, let’s review the renewal. Sam')
  await click('send-outreach')
  await click('skip')
  await click('handoff')
  await click('switch')
  await click('submit')
  await click('skip')
  await page.locator('[data-target="compare"]').waitFor()
  assert(await page.locator('[data-target="compare"]').isDisabled(), 'carrier question gates quote comparison')
  await click('answer')
  await click('compare')
  await page.getByRole('button', { name: 'Recommend', exact: true }).click()
  await click('recommend')
  await click('switch')
  const email = await page.getByRole('textbox', { name: 'Options email' }).inputValue()
  assert(email.includes('Our recommendation is Atlas'))
  assert((await page.locator('.evidence.solo').textContent()).includes('Atlas saves $2,400'))
  await click('send-options')
  await click('skip')
  await page.getByRole('heading', { name: 'Halcyon chose Atlas.' }).waitFor()
  assert(await page.getByText('$91,200', { exact: true }).isVisible())

  await page.goto('http://localhost:5183/?present=1&scene=brief#/halcyon-labs')
  const scenes = page.getByRole('navigation', { name: 'Presentation demo scenes' })
  await scenes.waitFor()
  await scenes.getByRole('button', { name: /^Placement/ }).click()
  await page.getByRole('heading', { name: 'Cyber goes to market at $5M. Choose where.' }).waitFor()
  await scenes.getByRole('button', { name: /^Quotes/ }).click()
  await page.getByRole('heading', { name: 'Compare two quotes.' }).waitFor()
  await scenes.getByRole('button', { name: /^Client decision/ }).click()
  await page.getByRole('heading', { name: 'The options for Priya, in plain language.' }).waitFor()
  await scenes.getByRole('button', { name: /^Brief/ }).click()
  await page.getByRole('heading', { name: 'Four things changed since Halcyon last renewed.' }).waitFor()
  await page.evaluate(() => Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))))
  await page.screenshot({ path: 'evidence/presenter-desktop.png' })

  await page.goto('http://localhost:5181/alex-renewal-discovery.html#11')
  await page.getByRole('button', { name: 'Run live demo' }).click()
  const frame = page.frameLocator('.live-demo-frame')
  await frame.getByRole('heading', { name: 'Halcyon Labs', exact: true }).waitFor()
  await frame.getByRole('navigation', { name: 'Presentation demo scenes' }).getByRole('button', { name: /^Quotes/ }).click()
  await frame.getByRole('heading', { name: 'Compare two quotes.' }).waitFor()
  await page.getByRole('button', { name: 'Back to slides', exact: true }).click()
  await page.locator('.live-demo-layer').waitFor({ state: 'hidden' })
  assert.equal(new URL(page.url()).hash, '#11')
  assert.deepEqual(errors, [])
  await context.close()

  for (const width of [698, 390]) {
    const compact = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' })
    const screen = await compact.newPage()
    await screen.goto('http://localhost:5183/?present=1&scene=brief#/halcyon-labs')
    await screen.getByRole('heading', { name: 'Halcyon Labs', exact: true }).waitFor()
    assert.equal(await screen.evaluate(() => document.documentElement.scrollWidth), width)
    const nav = screen.getByRole('navigation', { name: 'Presentation demo scenes' })
    await nav.getByRole('button', { name: /^Quotes/ }).click()
    await screen.getByRole('heading', { name: 'Compare two quotes.' }).waitFor()
    assert.equal(await screen.evaluate(() => document.documentElement.scrollWidth), width)
    await screen.screenshot({ path: `evidence/presenter-quotes-${width}.png` })
    await nav.getByRole('button', { name: /^Brief/ }).click()
    await screen.getByRole('heading', { name: 'Four things changed since Halcyon last renewed.' }).waitFor()
    await screen.screenshot({ path: `evidence/presenter-brief-${width}.png` })
    await compact.close()
  }
  console.log('PASS: entire renewal flow, source evidence, editable outreach, ownership handoffs, carrier-question gate, Atlas selection and note, client choice, presenter scene jumps, deck embedding and exact return, compact layouts and reduced motion.')
} finally {
  await browser.close()
}
